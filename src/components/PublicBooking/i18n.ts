// Bilingual strings for the public booking page.
//
// The clinic picks ONE regional language in Settings -> Public Booking. Every
// piece of page furniture then renders as `English (regional)` so a patient who
// reads either script can follow the form, and so reception -- who work in
// English -- still recognise every label when a patient calls about it.
//
// Deliberately NOT translated, and never should be:
//   * doctor names, qualifications and specialisations
//   * appointment type labels (they are clinical terms the clinic authored)
//   * the clinic's own name, address and notice text
//   * dates, times, fees and the booking reference
// Transliterating a drug, a degree or a doctor's name is how the wrong patient
// meets the wrong doctor, so those stay verbatim in English.

export interface RegionalLanguageOption {
  code: string;
  /** Name in English, for the settings dropdown. */
  english: string;
  /** Endonym, so the admin recognises the script they are switching on. */
  native: string;
}

