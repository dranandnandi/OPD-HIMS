export type TextKey = keyof typeof STRINGS;

/**
 * Renders page furniture in English, optionally followed by the clinic's
 * regional language in brackets. Callable for the bracketed form, with
 * `.en()` / `.regional()` for callers that want to lay the two out themselves
 * (long paragraphs read better stacked than parenthesised).
 */
export interface BookingTranslator {
  (key: TextKey): string;
  /** English only -- the canonical text. */
  en: (key: TextKey) => string;
  /** Regional only; '' when the clinic runs the page in English. */
  regional: (key: TextKey) => string;
  /** Selected language code, or '' for English-only. */
  language: string;
  /** Convenience flag for conditional two-line layouts. */
  bilingual: boolean;
}

export function createTranslator(language?: string | null): BookingTranslator {
  const code = isRegionalLanguage(language) ? language : '';

  const en = (key: TextKey) => STRINGS[key].en;
  const regional = (key: TextKey) =>
    code ? ((STRINGS[key] as Entry)[code] ?? '') : '';

  const translate = ((key: TextKey) => {
    const local = regional(key);
    return local ? `${en(key)} (${local})` : en(key);
  }) as BookingTranslator;

  translate.en = en;
  translate.regional = regional;
  translate.language = code;
  translate.bilingual = Boolean(code);

  return translate;
}

/** English-only translator, used before the clinic's settings have loaded. */
export const englishOnly = createTranslator(null);
